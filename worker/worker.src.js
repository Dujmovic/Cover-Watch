/* ---------- Web Push: VAPID keys, signing and encryption ---------- */
async function getVapid(env){
  const have=await env.KV.get('vapid','json');
  if(have&&have.pub&&have.priv)return have;
  const kp=await crypto.subtle.generateKey({name:'ECDSA',namedCurve:'P-256'},true,['sign','verify']);
  const v={pub:b64u(new Uint8Array(await crypto.subtle.exportKey('raw',kp.publicKey))),priv:await crypto.subtle.exportKey('jwk',kp.privateKey)};
  await env.KV.put('vapid',JSON.stringify(v));
  return v;
}
async function vapidAuth(endpoint,v,nowSec){
  const head=b64u(enc.encode(JSON.stringify({typ:'JWT',alg:'ES256'})));
  const body=b64u(enc.encode(JSON.stringify({aud:new URL(endpoint).origin,exp:(nowSec||Math.floor(Date.now()/1000))+12*3600,sub:APP_URL})));
  const key=await crypto.subtle.importKey('jwk',v.priv,{name:'ECDSA',namedCurve:'P-256'},false,['sign']);
  const sig=new Uint8Array(await crypto.subtle.sign({name:'ECDSA',hash:'SHA-256'},key,enc.encode(head+'.'+body)));
  return 'vapid t='+head+'.'+body+'.'+b64u(sig)+', k='+v.pub;
}
async function hkdf(salt,ikm,info,len){
  const k=await crypto.subtle.importKey('raw',ikm,'HKDF',false,['deriveBits']);
  return new Uint8Array(await crypto.subtle.deriveBits({name:'HKDF',hash:'SHA-256',salt,info},k,len*8));
}
/* RFC 8291 (aes128gcm). `fixed` lets the tests pin the server key and salt. */
async function encryptPush(sub,payload,fixed){
  const uaPub=unb64u(sub.keys.p256dh),auth=unb64u(sub.keys.auth);
  const uaKey=await crypto.subtle.importKey('raw',uaPub,{name:'ECDH',namedCurve:'P-256'},false,[]);
  const eph=fixed&&fixed.eph||await crypto.subtle.generateKey({name:'ECDH',namedCurve:'P-256'},true,['deriveBits']);
  const asPub=new Uint8Array(await crypto.subtle.exportKey('raw',eph.publicKey));
  const secret=new Uint8Array(await crypto.subtle.deriveBits({name:'ECDH',public:uaKey},eph.privateKey,256));
  const ikm=await hkdf(auth,secret,cat(enc.encode('WebPush: info\0'),uaPub,asPub),32);
  const salt=fixed&&fixed.salt||crypto.getRandomValues(new Uint8Array(16));
  const cek=await hkdf(salt,ikm,enc.encode('Content-Encoding: aes128gcm\0'),16);
  const nonce=await hkdf(salt,ikm,enc.encode('Content-Encoding: nonce\0'),12);
  const aes=await crypto.subtle.importKey('raw',cek,'AES-GCM',false,['encrypt']);
  const ct=new Uint8Array(await crypto.subtle.encrypt({name:'AES-GCM',iv:nonce},aes,cat(payload,new Uint8Array([2]))));
  const rs=new Uint8Array([0,0,16,0]);
  return cat(salt,rs,new Uint8Array([asPub.length]),asPub,ct);
}
async function sendPush(sub,v,message){
  const body=await encryptPush(sub,enc.encode(JSON.stringify(message)));
  const r=await fetch(sub.endpoint,{method:'POST',headers:{
    Authorization:await vapidAuth(sub.endpoint,v),'Content-Encoding':'aes128gcm','Content-Type':'application/octet-stream',
    TTL:'3600',Urgency:'high'},body});
  let text='';
  if(r.status<200||r.status>=300){try{text=(await r.text()).slice(0,160)}catch(e){}}
  return {status:r.status,text};
}

