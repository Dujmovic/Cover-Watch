/* Keeps only the games a bet points at, in the same shape the app uses. */
function pickGames(j,lg,want,out){
  (j&&j.events||[]).forEach(ev=>{
    const id=String(ev.id);if(!want[id])return;
    const comp=(ev.competitions||[])[0];if(!comp)return;
    const cs=comp.competitors||[];
    const home=cs.find(c=>c.homeAway==='home'),away=cs.find(c=>c.homeAway==='away');
    if(!home||!away||!home.team||!away.team)return;
    const t=(ev.status&&ev.status.type)||{};
    let status='pre';
    if(t.state==='in')status='live';
    else if(t.state==='post'&&t.completed)status='final';
    const detail=status==='final'?'Final':(t.shortDetail||t.detail||'');
    const sc=c=>{if(status==='pre')return null;const n=Number(c.score);return isNaN(n)?null:n};
    const team=(c,score)=>({abbr:c.team.abbreviation||c.team.shortDisplayName||'?',name:c.team.shortDisplayName||c.team.name||c.team.displayName||c.team.abbreviation,score});
    let start=null;try{start=new Date(ev.date).toISOString()}catch(e){}
    out['feed:'+lg+':'+id]={league:lg,id,status,start,detail,away:team(away,sc(away)),home:team(home,sc(home))};
  });
}

