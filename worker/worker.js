    const e={phase,m,L,win,stake,total:a+h,scale:isTotal?L.tscale:L.scale};
    e.labels=isTotal?(bet.side==='over'?['Short','Line','Over']:['Busted','Line','Under']):isSpread?['Missing','Cover line','Covering']:['Behind','Even','Ahead'];
    e.cap=isTotal?(bet.side==='over'?'vs line':'room left'):isSpread?'vs line':'lead';
    if(phase==='pre'){e.st='idle';e.word='Not started';e.num='—';e.sub='';return e;}
    const need=m<0?Math.floor(-m)+1:0;
    const k=m>0?Math.ceil(m)-1:0;
    e.need=need;e.room=k;
    e.num=m===0?'0':signed(m);
