/* Keeps only the games a bet points at, in the same shape the app uses. */
function pickGames(j,lg,want,out){
  (j&&j.events||[]).forEach(ev=>{
    const id=String(ev.id);if(!want[id])return;
    const comp=(ev.competitions||[])[0];if(!comp)return;
    const cs=comp.competitors||[];
    const home=cs.find(c=>c.homeAway==='home'),away=cs.find(c=>c.homeAway==='away');
    if(!home||!away||!home.team||!away.team)return;
    const t=(ev.status&&ev.status.type)||{};
    let status='pre';
    if(t.state==='in')status='live';
    else if(t.state==='post'&&t.completed)status='final';
    const detail=status==='final'?'Final':(t.shortDetail||t.detail||'');
    const sc=c=>{if(status==='pre')return null;const n=Number(c.score);return isNaN(n)?null:n};
    const team=(c,score)=>({abbr:c.team.abbreviation||c.team.shortDisplayName||'?',name:c.team.shortDisplayName||c.team.name||c.team.displayName||c.team.abbreviation,score});
    let start=null;try{start=new Date(ev.date).toISOString()}catch(e){}
    out['feed:'+lg+':'+id]={league:lg,id,status,start,detail,away:team(away,sc(away)),home:team(home,sc(home))};
  });
}

/* ---------- bets from the phone ---------- */
const keepNum=v=>v==null||v===''?v:num(v);
function cleanLeg(l,tk){
  if(!l||typeof l.gameKey!=='string'||l.gameKey.indexOf('feed:')!==0||l.gameKey.split(':').length!==3)return null;
  if(!LG[l.league]||['spread','moneyline','total'].indexOf(l.type)<0)return null;
  const o={gameKey:l.gameKey,league:l.league,type:l.type,side:String(l.side),line:num(l.line)};
  if(l.odds!=null&&l.odds!=='')o.odds=num(l.odds);
  const s=l.snap||{};
  o.snap={qd:/^\d{8}$/.test(String(s.qd||''))?String(s.qd):null,start:typeof s.start==='string'?s.start:null};
  return o;
}
function cleanBet(b){
  if(!b||typeof b.id!=='string')return null;
  const o={id:b.id.slice(0,40),stake:num(b.stake),created:num(b.created)};
  if(b.kind==='teaser'||b.kind==='parlay'){
    if(!Array.isArray(b.legs)||!b.legs.length||b.legs.length>16)return null;
    const legs=b.legs.map(cleanLeg);if(legs.some(x=>!x))return null;
    o.kind=b.kind;o.legs=legs;o.odds=keepNum(b.odds);
    if(b.kind==='teaser'){o.points=num(b.points);o.pleaser=!!b.pleaser;o.push=['lose','reduce','refund'].indexOf(b.push)>=0?b.push:'reduce'}
    return o;
  }
  const l=cleanLeg(b);if(!l)return null;
  return Object.assign(o,l,{odds:num(b.odds)});
}
const startOf=b=>{
  let m=Infinity;
  for(const l of legsOf(b)){const t=l.snap&&l.snap.start?Date.parse(l.snap.start):NaN;if(isNaN(t))return null;if(t<m)m=t}
  return m===Infinity?null:m;
};

/* ---------- alert detection (same rules as the app) ---------- */
function mkItem(b,games){
  if(isTk(b)){
    const gs=b.legs.map(l=>games[l.gameKey]);
    if(gs.some(g=>!g))return null;
    return {b,games:gs,g:gs[0],e:b.kind==='parlay'?CW.evaluateParlay(b,gs):CW.evaluateTeaser(b,gs)};
  }
  const g=games[b.gameKey];if(!g)return null;
  return {b,g,e:CW.evaluate(b,g)};
}
function detect(bets,games,seenIn,now,N){
  const seen={bets:Object.assign({},seenIn&&seenIn.bets),games:Object.assign({},seenIn&&seenIn.games)};
  if(seenIn&&seenIn.last)seen.last=seenIn.last;
  const before=JSON.stringify(seen);
  const real=[];
  bets.forEach(b=>{const it=mkItem(b,games);if(it)real.push(it)});
  const mine={},scored={},fresh=[];
  real.forEach(it=>{
    if(it.e.phase==='final')return;
    const gs=isTk(it.b)?it.games:[it.g];
    legsOf(it.b).forEach((ent,i)=>{
      const k=ent.gameKey,g=gs[i];
      if(!k||!g)return;
      const m=mine[k]||(mine[k]={g:g,its:[],old:false});
      if(m.its.indexOf(it)<0)m.its.push(it);
      if(!(it.b.created&&now-it.b.created<60000))m.old=true;
    });
  });
  Object.keys(mine).forEach(k=>{
    const g=mine[k].g,a=Number(g.away.score)||0,h=Number(g.home.score)||0,prev=seen.games[k];
    if(prev&&(prev.a!==a||prev.h!==h||prev.p!==g.status)){
      const da=a-prev.a,dh=h-prev.h;
      if(mine[k].old&&LG[g.league]&&LG[g.league].football&&g.status==='live'&&da>=0&&dh>=0&&(da>0||dh>0))scored[k]={phrase:scorePhrase(g,da,dh,false),g:g,its:mine[k].its};
    }
    if(!prev||prev.a!==a||prev.h!==h||prev.p!==g.status)seen.games[k]={a:a,h:h,p:g.status};
  });
  const used={};
  bets.forEach(b=>legsOf(b).forEach(l=>{used[l.gameKey]=1}));
  Object.keys(seen.games).forEach(k=>{if(!used[k])delete seen.games[k]});
  real.forEach(it=>{
    const id=it.b.id,cur=stateOf(it),prev=seen.bets[id];
    if(!prev){seen.bets[id]=cur;return}
    if(sameState(prev,cur))return;
    seen.bets[id]=cur;
    if(it.b.created&&now-it.b.created<60000)return;
    const a=describeChange(it,prev,cur,N.score?scoredFor(it,scored):'');
    if(a){a.games=gamesOf(it);fresh.push(a)}
  });
  const ids={};bets.forEach(b=>{ids[b.id]=1});
  Object.keys(seen.bets).forEach(id=>{if(!ids[id])delete seen.bets[id]});
  const wanted=a=>N.on&&N[a.kind];
  const covered={};
  fresh.filter(wanted).forEach(a=>a.games.forEach(k=>{covered[k]=1}));
  Object.keys(scored).forEach(k=>{
    if(covered[k])return;
    const sc=scored[k],g=sc.g;
    const sts=sc.its.map(i=>i.e.st).filter((x,i,arr)=>arr.indexOf(x)===i);
    const names=sc.its.slice(0,3).map(i=>(isTk(i.b)?ticketTitle(i.b):pickTitle(i.b,i.g))+' '+i.e.word.toLowerCase());
    fresh.push({id:sc.its[0].b.id,t:now,kind:'score',st:sts.length===1?sts[0]:'idle',title:sc.phrase,games:[k],
      msg:scoreText(g)+(g.detail?' · '+g.detail:'')+' · '+names.join('; ')+(sc.its.length>3?'; +'+(sc.its.length-3)+' more':'')});
  });
  return {seen,alerts:fresh.filter(wanted),changed:JSON.stringify(seen)!==before};
}
function messagesFor(alerts,now){
  if(alerts.length>3)return [{title:EMO.idle+' '+alerts.length+' new alerts',body:'Open Cover Watch to see each one.',tag:'multi:'+now,t:now}];
  return alerts.map(a=>({title:(EMO[a.st]||EMO.idle)+' '+a.title,body:a.msg,tag:a.kind+':'+a.id+':'+hash(a.msg),t:a.t||now}));
}

