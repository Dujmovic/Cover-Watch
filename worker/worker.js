function describeChange(it,prev,cur,sc){
  const b=it.b,e=it.e,tk=isTk(b);
  const a={id:b.id,t:Date.now(),st:e.st,title:tk?ticketTitle(b):pickTitle(b,it.g)};
  const where=tk?'':' · '+scoreText(it.g);
  const lead=sc?sc+' · ':'';
  if(cur.p==='final'&&prev.p!=='final'){
    a.kind='final';
    const amt=e.stake>0&&e.net!=null?' '+CW.smoney(e.net):'';
    let head=e.outcome==='won'?'Won'+amt:e.outcome==='lost'?'Lost'+amt:'Push';
    if(e.outcome==='won'&&e.net===null)head='Won. Payout reduced, check your book';
    const why=tk&&e.outcome==='lost'?deadText(it)+(e.early?' · settled early':''):e.sub;
    a.msg=head+(why?' · '+why:'');
    return a;
  }
  if(tk){
    const pl=prev.l||'',cl=cur.l||'',ch=[];
    for(let i=0;i<cl.length;i++)if(pl[i]!==cl[i])ch.push(i);
    if(!ch.length)return null;
    const starts=ch.every(i=>pl[i]==='i');
    const bits=ch.map(i=>{
      const le=e.legs[i],t=pickTitle(le.leg,le.game,le.adj),c=cl[i];
      if(pl[i]==='i')return t+' is under way';
      if(c==='W')return t+' won';
      if(c==='L')return t+' lost';
      if(c==='P')return t+' landed on the number';
      return t+' is now '+LEGW[c];
    });
    a.kind=starts?'start':'flip';
    if(starts)a.st='idle';
    a.msg=(starts?'':lead)+bits.join('. ')+' · '+e.covering+' of '+e.n+' covering';
    return a;
  }
  if(prev.p==='pre'&&cur.p==='live'){a.kind='start';a.st='idle';a.msg='Game is under way'+where;return a}
  a.kind='flip';
  a.msg=lead+'Now '+e.word.toLowerCase()+(e.sub?' · '+e.sub:'')+where;
  return a;
}

